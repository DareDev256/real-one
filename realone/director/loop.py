"""The agentic director: Muse Wonder drives the run through tools, watches its own cut, revises once.

Which driver, and why: the docs CONFIRM tool calling for muse-wonder-1.0 (dev.meta.ai/docs/models, Wonder paragraph;
function tools and function_call_output on the Responses API, docs/tool-calling). So the default driver is the
model: Wonder decides which tool to call next, with what arguments, and when to stop. Every tool-calling example in
the docs uses muse-spark-1.3, not Wonder, so `--driver code` keeps the same loop with our code as the orchestrator
and Wonder making each decision in JSON (one `decide` call), as the fallback for the first keyed run.

Code owns the limits either way: turns, paid calls, dollars, one revision pass, renders per section (tools.py).
"""
import json

from realone.common import Refuse
from realone.director.backend import text_part, user
from realone.director.budget import LOOP_BASE_TOKENS, LOOP_GROWTH_TOKENS, MAX_REVISIONS
from realone.director.schema import DECISION_SCHEMA, parse_json, validate
from realone.director.tools import TOOL_SPECS

LOOP_INSTRUCTIONS = f"""You are the director of a music video and you run the production through tools.
The treatment (yours, already checked) is the plan. Work in this order:
1. generate_world for each section the phone take covers (the prompt is that section's world_prompt, verbatim);
2. render_section for each covered section with its treatment look and freeze;
3. watch each render and read its notes and measured checks;
4. if a note shows a section fighting its subtext, use the ONE revision pass: up to {MAX_REVISIONS} revise calls
   (swap a world_prompt, change a look, or move the freeze to another hook), then re-render the changed covered
   sections (generate_world first if a world_prompt changed) and watch them once;
5. finish with a short summary.
Rules the tools enforce: the treatment is the single source of truth, one revision pass, at most two renders per
section, only covered sections render, a literal world_prompt is refused. Call several tools in one turn when they
do not depend on each other. Keep text short; the tools do the work."""

DECIDE_INSTRUCTIONS = f"""You are the director. Below are your treatment and your notes from watching each rendered
section. Decide the ONE revision pass: up to {MAX_REVISIONS} changes (world_prompt, look, or freeze moved to another
hook with value "true"), or none if every section serves its subtext. A new world_prompt is a place with no people
and none of the section's lyric words. Return JSON."""


def coverage(timeline, clip, song, sync_near=None):
    """-> (covered section indices, sync dict, clip seconds). The renderer refuses a section the take does not
    cover; checking first saves a subprocess and tells the model what it can render."""
    from realone.media import probe, stream
    from realone.sync import sync_clip
    sy = sync_clip(song, clip, sync_near)
    info = probe(clip)
    vlen = float((stream(info, "video") or {}).get("duration") or info["format"]["duration"])
    off = sy["offset_s"]
    covered = [s["index"] for s in timeline["sections"]
               if s["start_s"] - off >= -1e-3 and s["end_s"] - off <= vlen + 1e-3]
    return covered, {k: sy[k] for k in ("offset_s", "offset_ms", "r_peak", "margin", "resolved_by")}, vlen


def _context(state):
    secs = []
    for s in state.timeline["sections"]:
        p = state.plan(s["index"])
        secs.append({"index": s["index"], "role": s["role"], "is_hook": s.get("is_hook", False),
                     "start_s": round(s["start_s"], 2), "end_s": round(s["end_s"], 2),
                     "covered_by_take": s["index"] in state.covered, "lyric": state.lyrics.get(s["index"], []),
                     **{k: p[k] for k in ("subtext", "world_prompt", "look", "freeze", "camera_energy")}})
    return {"song_subtext": state.treatment.get("song_subtext"), "covered_sections": state.covered,
            "sections": secs,
            "note": ("DRY RUN: renders use test plates and a drawn figure; worlds are not generated"
                     if state.dry_run else "keyed run: worlds are generated by Muse Image, masks by SAM 3.1")}


def run_model(backend, tools, state, max_turns=8):
    """Wonder drives: function calls in, function_call_output back, until finish or a cap."""
    first = user(text_part("Direct this run. Treatment, coverage and lyrics (JSON):\n" +
                           json.dumps(_context(state), indent=1)))
    turn = backend.respond(purpose="loop", instructions=LOOP_INSTRUCTIONS, input=[first], tools=TOOL_SPECS,
                           effort="medium", est_input_tokens=LOOP_BASE_TOKENS)
    turns = 1
    while True:
        state.log.append({"turn": turns, "source": turn.source, "text": turn.text[:1200],
                          "calls": [{"name": c["name"], "arguments": c["arguments"]} for c in turn.calls],
                          "usd": round(turn.usd, 5)})
        if turn.text.strip():
            print(f"director [{turn.source}] {turn.text.strip()[:300]}")
        if not turn.calls:
            if state.finished is None:
                state.finished = f"(model stopped without calling finish) {turn.text.strip()[:400]}"
            return "model stopped"
        outputs = []
        for c in turn.calls:
            out = tools.dispatch(c["name"], c["arguments"])
            print(f"  tool {c['name']}: {'ok' if out.get('ok') else 'ERROR ' + out.get('error', '')[:200]}")
            outputs.append({"type": "function_call_output", "call_id": c["call_id"], "output": json.dumps(out)})
        if state.finished is not None:
            return "finished"
        if turns >= max_turns:
            state.finished = f"(turn cap {max_turns} reached before finish)"
            return "turn cap"
        turn = backend.respond(purpose="loop", instructions=LOOP_INSTRUCTIONS, input=outputs, tools=TOOL_SPECS,
                               previous_id=turn.id, effort="medium",
                               est_input_tokens=LOOP_BASE_TOKENS + turns * LOOP_GROWTH_TOKENS)
        turns += 1


def run_code(backend, tools, state):
    """Our code orchestrates the same tools; Wonder makes the one revision decision in JSON."""
    def call(name, **args):
        out = tools.dispatch(name, args)
        print(f"  tool {name}({', '.join(f'{k}={v!r}'[:60] for k, v in args.items())}): "
              f"{'ok' if out.get('ok') else 'ERROR ' + out.get('error', '')[:200]}")
        return out

    def cut(i):
        p = state.plan(i)
        w = state.worlds.get(i)
        if not w or w["prompt"] != " ".join(p["world_prompt"].split()):
            if not call("generate_world", section=i, prompt=p["world_prompt"]).get("ok"):
                return None
        r = call("render_section", section=i, look=p["look"], freeze=p["freeze"])
        return call("watch", render_path=r["video"]) if r.get("ok") else None

    for i in state.covered:
        cut(i)
    ctx = {"treatment": _context(state), "watched": [{k: w[k] for k in ("section", "verdict", "notes", "suggestion",
                                                                        "measured")} for w in state.watches]}
    turn = backend.respond(purpose="decide", instructions=DECIDE_INSTRUCTIONS,
                           input=[user(text_part(json.dumps(ctx, indent=1)))], schema=DECISION_SCHEMA,
                           schema_name="revision_pass", effort="medium",
                           est_input_tokens=LOOP_BASE_TOKENS + 800 * len(state.watches))
    dec, errs = parse_json(turn.text)
    errs = errs or validate(dec, DECISION_SCHEMA)
    state.log.append({"step": "decide", "source": turn.source, "decision": dec, "errors": errs})
    if errs:
        raise Refuse("the revision decision did not validate: " + "; ".join(errs[:6]))
    print(f"director [{turn.source}] decision: {dec['why'][:300]}")
    for r in dec["revisions"]:
        call("revise", section=r["section"], field=r["field"], value=r["value"], because=r["because"])
    for i in list(state.revision["changed"]):
        if i in state.covered and i in state.renders:
            cut(i)
    call("finish", summary=f"code driver: rendered {sorted(state.renders)}, revisions "
                           f"{[(c['section'], c['field']) for c in state.revision['changes']]}; {dec['why'][:200]}")
    return "finished"
